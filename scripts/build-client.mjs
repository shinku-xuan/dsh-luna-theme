/** Build the browser entry in DSH's lazy CommonJS module format. */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = fileURLToPath(new URL('../', import.meta.url))
const entry = 'src/client/index.js'
const modules = new Map()
const external = new Set(['react', '@deepseek-ai/dsh-client-store', '@deepseek-ai/dsh-client-ui-primitives'])
const resolve = (parent, specifier) => path.posix.normalize(path.posix.join(path.posix.dirname(parent), specifier))

function collect(id) {
  if (modules.has(id)) return
  const file = path.resolve(root, id)
  if (!file.startsWith(path.resolve(root) + path.sep)) throw new Error('Client import escapes the package: ' + id)
  const extension = path.extname(id)
  if (extension === '.json') {
    modules.set(id, 'module.exports = ' + JSON.stringify(JSON.parse(fs.readFileSync(file, 'utf8'))) + ';')
    return
  }
  if (extension === '.css') {
    modules.set(id, 'module.exports = ' + JSON.stringify(fs.readFileSync(file, 'utf8')) + ';')
    return
  }
  if (extension === '.webp') {
    modules.set(id, 'module.exports = ' + JSON.stringify('data:image/webp;base64,' + fs.readFileSync(file).toString('base64')) + ';')
    return
  }
  if (extension !== '.js') throw new Error('Unsupported client import: ' + id)
  const source = fs.readFileSync(file, 'utf8')
  const parsed = ts.createSourceFile(id, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const emitted = ts.transpileModule(source, { fileName: id, reportDiagnostics: true,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } })
  const errors = emitted.diagnostics.filter(item => item.category === ts.DiagnosticCategory.Error)
  if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, { getCanonicalFileName: value => value, getCurrentDirectory: () => root, getNewLine: () => '\n' }))
  modules.set(id, emitted.outputText.trim())
  for (const statement of parsed.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue
    const specifier = statement.moduleSpecifier.text
    if (specifier.startsWith('.')) collect(resolve(id, specifier))
    else if (!external.has(specifier)) throw new Error('Client import is outside the DSH browser baseline: ' + specifier)
  }
}
collect(entry)
const factories = [...modules].map(([id, code]) => JSON.stringify(id) + ': (require, module, exports) => {\n' + code + '\n}').join(',\n')
const output = `/** Generated by npm run build; edit src/client instead. */
window.__ModuleLoader__.load({
  id: 'dsh-luna-theme',
  factory(moduleRequire) {
    const factories = {${factories}};
    const loaded = new Map();
    const resolve = (parent, specifier) => {
      const parts = parent.split('/'); parts.pop();
      for (const part of specifier.split('/')) {
        if (part === '..') parts.pop();
        else if (part !== '.') parts.push(part);
      }
      return parts.join('/');
    };
    const materialize = id => {
      if (loaded.has(id)) return loaded.get(id).exports;
      const module = { exports: {} }; loaded.set(id, module);
      const require = specifier => specifier.startsWith('.') ? materialize(resolve(id, specifier)) : moduleRequire(specifier);
      factories[id](require, module, module.exports);
      return module.exports;
    };
    return materialize(${JSON.stringify(entry)}).default;
  },
});
`
const destination = path.join(root, 'lib', 'client.js')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) throw new Error('lib/client.js is stale. Run npm run build.')
  console.log('Client bundle matches the source tree.')
} else {
  fs.mkdirSync(path.dirname(destination), { recursive: true })
  fs.writeFileSync(destination, output)
  console.log(`Built lib/client.js from ${modules.size} package modules.`)
}
